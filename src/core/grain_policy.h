// ============================================================================
//  LumenPlayer - 胶片颗粒策略
//  ---------------------------------------------------------------------------
//  所属层次：产品层（C 层）
//  职责    ：估计原片的颗粒/噪声强度，并决定超分后要不要、以及以多大强度
//            把颗粒"回注"回去。
//
//  为什么必须做（这是老片修复最容易做错的一步）：
//    超分模型天然会平滑高频细节。胶片颗粒是第一受害者——它被当成噪声抹掉，
//    结果是脸变成塑料质感、暗部出现色块、运动时出现"呼吸"闪烁。
//    观众的评价通常不是"不够清晰"，而是"看着不真实"。
//
//  正确做法：在送入超分前把高频残差（颗粒层）提出来缓存，
//            超分完成后按可控强度加回输出帧。强度过高会让画面发脏，
//            过低则回到塑料脸，所以需要按实测颗粒强度自适应。
// ============================================================================
#pragma once

#include <cstdint>
#include <string>

#include "frame_buffer.h"

namespace lumen {

// ---------------------------------------------------------------------------
// 颗粒估计结果
// ---------------------------------------------------------------------------
struct GrainEstimate {
  double sigma = 0.0;      // 噪声标准差（8bit 亮度尺度）
  double flat_ratio = 0.0; // 参与估计的平坦区域占比（过低说明估计不可信）
  int blocks_used = 0;     // 实际参与统计的块数
  std::string detail;      // 人可读说明
};

// 估计颗粒强度。
// 参数说明：
//   y/w/h/stride —— 亮度平面
//   block_size   —— 分块边长，默认 16（块太小统计不稳定，太大则混入细节）
// 算法 ：
//   1. 按块计算平均梯度，取梯度最低的若干块（这些区域近似平坦，
//      其残差主要来自颗粒而非景物细节）；
//   2. 在平坦块上计算拉普拉斯响应的中位数绝对值，
//      用 σ = median(|L|) / 0.6745 / √6 换算为高斯噪声标准差（Donoho 估计）。
//   之所以先筛平坦块：直接全图取中位数会把纹理细节算成噪声，
//   导致颗粒强度被高估 2—3 倍，回注后画面发脏。
GrainEstimate EstimateGrain(const uint8_t* y, int w, int h, int stride, int block_size = 16);

GrainEstimate EstimateGrain(const FrameBuffer& frame, int block_size = 16);

// ---------------------------------------------------------------------------
// 颗粒回注决策
// ---------------------------------------------------------------------------
struct GrainDecision {
  bool enabled = false;   // 是否启用回注
  double amplitude = 0.0; // 回注强度（1.0 = 完全复原，0.0 = 完全去掉）
  double sigma = 0.0;     // 估计出的原始颗粒强度
  bool needs_denoise = false; // 是否建议先做轻度降噪（颗粒过强且疑似视频噪声）
  std::string reason;
};

// 根据颗粒估计结果给出回注决策。
// 参数说明：est 为 EstimateGrain 的输出；is_animation 影响阈值
//           （动画素材的平涂区域对颗粒更敏感，强度要给低一些）。
GrainDecision DecideGrain(const GrainEstimate& est, bool is_animation = false);

} // namespace lumen
